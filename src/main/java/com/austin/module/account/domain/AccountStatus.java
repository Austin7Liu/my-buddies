package com.austin.module.account.domain;

public enum AccountStatus {

    /**
     * 正常状态。
     * 账户可以正常登录和使用当前身份等级允许的功能。
     */
    ACTIVE,

    /**
     * 注销待处理状态。
     * 用户已申请注销，但仍处于 7 天冷静期，可以撤销注销申请。
     * 冷静期内手机号仍与该账户绑定，不能用于注册新账户。
     */
    CANCEL_PENDING,

    /**
     * 已注销状态。
     * 注销冷静期已经结束，账户正式注销。
     * 手机号解除绑定，可以用于重新注册，但必要的风控和审计记录仍需保留。
     */
    CANCELLED,

    /**
     * 永久封禁状态。
     * 账户因确认的严重违规被冻结，禁止登录和使用平台功能。
     * 封禁记录不能通过注销账户或更换手机号清除。
     */
    BANNED
}